export const CATALOGS: Record<Locale, Catalog> = { en, zh, 'zh-HK': zhHK, fr, hi, de, ja, ko, es };

function isLocale(v: string): v is Locale {
  return (LOCALES as readonly string[]).includes(v);
}

// matchLocale —— a language tag (any case: zh-HK, zh-hk, en-US) → a supported locale: the whole tag
// when it is one (zh-HK), else its base language (en-US → en), else null.
function matchLocale(tag: string): Locale | null {
  const want = tag.trim().toLowerCase();
  const whole = LOCALES.find((l) => l.toLowerCase() === want);
  if (whole !== undefined) return whole;
  const base = want.split('-')[0] ?? '';
  return isLocale(base) ? base : null;
}

// resolveLocale —— the PAGE's language, English by default: explicit (the widget's `lang` prop) wins;
// else the language the page declares (<html lang>; a bilingual page's toggle sets it, see
// usePageLang); else English. Never the reader's browser language: a page is written in one language
// by its author, and a widget that switched to the reader's language put "想问什么都可以…" on an
// English cover letter (owner, 2026-09-28: "widget 的 default 都应该是英文"). Never the stored
// `sm-lang` either: localStorage is shared by every page on the instance, so one bilingual page's
// choice put "向 AI 提问" on an English letter (owner, 2026-09-30). Never throws (no document).
export function resolveLocale(explicit?: string): Locale {
  if (explicit !== undefined) {
    const given = matchLocale(explicit);
    if (given !== null) return given;
  }
  try {
    const declared = matchLocale(document.documentElement.lang || '');
    if (declared !== null) return declared;
  } catch { /* no document */ }
  return 'en';
}

// WidgetLang —— the language a widget was given (its `lang` prop), for everything rendered inside
// it (the BYOK panel, cards) without threading a prop through each layer.
export const WidgetLang = createContext<string | undefined>(undefined);

// ChatLangProvider —— a host that knows its language (the app, from its locale-in-URL routing)
// states it once; every chat view below speaks it. A component, not the context's .Provider, so a
// server component (the app's root layout) can render it.
export function ChatLangProvider({ lang, children }: { lang: string; children: ReactNode }): ReactNode {
  return <WidgetLang.Provider value={lang}>{children}</WidgetLang.Provider>;
}

export type T = (key: MessageKey, vars?: Record<string, string>) => string;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string>): string {
  let s = CATALOGS[locale][key];
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, v);
  return s;
}

// useT —— t() in the page's language (see resolveLocale). A given `lang` renders from the first
// render (it is known at build time, so the prerender matches); otherwise English first, then the
// page's declared language right after mount — and again whenever the page changes it (a bilingual
// page's toggle sets <html lang> after this widget mounted).
export function useT(): T {
  const explicit = useContext(WidgetLang);
  // First render: only what the page's source says (no browser read, so it matches the prerender).
  const [locale, setLocale] = useState<Locale>(explicit !== undefined && isLocale(explicit) ? explicit : 'en');
  useEffect(() => {
    const apply = () => { setLocale(resolveLocale(explicit)); };
    apply();
    if (explicit !== undefined && isLocale(explicit)) return undefined;
    const obs = new MutationObserver(apply);
    obs.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
    return () => { obs.disconnect(); };
  }, [explicit]);
  return (key, vars) => translate(locale, key, vars);
}

// useChatT —— t() for one chat view's keys (`<ns>.<key>` in the catalogs). The chat views came from
// the app, whose next-intl calls read `useTranslations(ns)` then `t(key, vars)`; this keeps that call
// shape, and the KeyIn type still rejects a key the catalog does not have.
type ChatNs = 'transcript' | 'attachments' | 'dock' | 'composer' | 'tools' | 'voice' | 'live' | 'wiki';
type KeyIn<N extends string> = MessageKey extends infer M
  ? M extends `${N}.${infer K}` ? K : never
  : never;

export function useChatT<N extends ChatNs>(ns: N): (key: KeyIn<N>, vars?: Record<string, string | number>) => string {
  const t = useT();
  return (key, vars) => {
    const full = `${ns}.${key}`;
    const strVars = Object.fromEntries(Object.entries(vars ?? {}).map(([k, v]) => [k, String(v)]));
    return isMessageKey(full) ? t(full, strVars) : full;
  };
}

function isMessageKey(k: string): k is MessageKey {
  return k in en;
}
